def current_lang():
    lang = get_language() or settings.LANGUAGE_CODE
    return "en" if lang.startswith("en") else "ar"


def tr(key, *args):
    entry = T.get(key)
    if entry is None:
        text = key
    else:
        text = entry[1] if current_lang() == "en" else entry[0]
    return text.format(*args) if args else text


tr_lazy = lazy(tr, str)
